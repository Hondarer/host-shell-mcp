#!/bin/sh
# Place the VS Code CLI and server fetched by fetch.sh in the layout that Remote - SSH uses, so
# that connecting needs no download on the target.
# ~/.vscode-server/code-<C> is a wrapper that pins the agent host to <C>, the commit of the client
# that runs it; the CLI itself is ~/.vscode-server/host-shell-cli/code-<C>.
# Usage: place.sh DIST_DIR          place DIST_DIR (COMMIT, SHA256SUMS, cli.tar.gz, server.tar.gz)
#                                   and put its commit first in lru.json
#        place.sh --prune COMMIT    delete every placed version except COMMIT (VS Code Server stopped)
set -eu
. "$(cd "$(dirname "$0")" && pwd)/common.sh"

# Write lru.json with Stable-$1 first, keeping the other entries whose folder still exists.
# The agent host reads this list to find a cached server when it cannot reach the update service.
write_lru() {
  first=Stable-$1
  rest=""
  if [ -f "$HSVR_LRU" ]; then
    for e in $(grep -o '"[A-Za-z]*-[0-9a-f]\{40\}"' "$HSVR_LRU" | tr -d '"'); do
      [ "$e" = "$first" ] && continue
      [ -d "$HSVR_SERVERS_DIR/$e" ] || continue
      rest="$rest,\"$e\""
    done
  fi
  printf '["%s"%s]' "$first" "$rest" >"$HSVR_LRU.tmp"
  mv "$HSVR_LRU.tmp" "$HSVR_LRU"
}

prune() {
  C=$1
  check_commit "$C"
  [ -d "$HSVR_SERVERS_DIR/Stable-$C/server" ] && wrapped "$C" ||
    die "Stable-$C is not placed by place.sh; nothing pruned"
  if vscode_running; then die "VS Code Server is running; stop it first with cleanup.sh"; fi
  for d in "$HSVR_SERVERS_DIR"/Stable-*; do
    [ -e "$d" ] || continue
    [ "$d" = "$HSVR_SERVERS_DIR/Stable-$C" ] && continue
    rm -rf "$d"
    echo "removed $(basename "$d")"
  done
  for f in "$HSVR_VSCODE_DIR"/code-* "$HSVR_CLI_DIR"/code-*; do
    [ -e "$f" ] || continue
    [ "${f##*/}" = "code-$C" ] && continue
    rm -f "$f"
    echo "removed $f"
  done
  write_lru "$C"
  echo "lru.json: $(cat "$HSVR_LRU")"
}

if [ "${1:-}" = "--prune" ]; then
  prune "${2:-}"
  exit 0
fi

D=${1:?usage: place.sh DIST_DIR | --prune COMMIT}
require_cmd tar gzip sha256sum df
for f in COMMIT SHA256SUMS cli.tar.gz server.tar.gz; do
  [ -f "$D/$f" ] || die "missing $D/$f; send the folder that fetch.sh wrote"
done
C=$(cat "$D/COMMIT")
check_commit "$C"
(cd "$D" && sha256sum -c SHA256SUMS) || die "SHA-256 mismatch in $D"
server_commit() {
  sed -n 's/.*"commit": *"\([0-9a-f]\{40\}\)".*/\1/p' "$1/product.json" 2>/dev/null | head -n 1
}

# A server that is already placed may be running; keep it and rewrite only the wrapper and CLI.
keep=no
if [ "$(server_commit "$HSVR_SERVERS_DIR/Stable-$C/server")" = "$C" ]; then
  keep=yes
elif [ -e "$HSVR_SERVERS_DIR/Stable-$C" ] &&
  pgrep -u "$(id -u)" -f "^$hsvr_home_re/cli/servers/Stable-$C/" >/dev/null 2>&1; then
  die "Stable-$C is incomplete and in use; stop VS Code Server with cleanup.sh and place again"
fi
if [ $keep = no ]; then
  free=$(free_mib "$HSVR_VSCODE_DIR")
  [ "$free" -ge "$HSVR_PLACE_MIB" ] ||
    die "not enough disk space: $HSVR_PLACE_MIB MiB needed under $HSVR_VSCODE_DIR, $free MiB free"
fi

mkdir -p "$HSVR_SERVERS_DIR" "$HSVR_CLI_DIR"
t=$(mktemp -d "$HSVR_VSCODE_DIR/.place.XXXXXX")
trap 'rm -rf "$t"' EXIT
tar -C "$t" -xzf "$D/cli.tar.gz"
[ -f "$t/code" ] || die "cli.tar.gz has no code binary"
if [ $keep = no ]; then
  mkdir "$t/server"
  tar -C "$t/server" -xzf "$D/server.tar.gz" --strip-components=1
  got=$(server_commit "$t/server")
  [ "$got" = "$C" ] || die "server commit $got does not match $C"
fi

mv -f "$t/code" "$HSVR_CLI_DIR/code-$C"
# Remote - SSH starts ~/.vscode-server/code-<C> when it exists and watches the PID it spawned, so
# the wrapper execs the CLI in place. Without the pin the agent host runs the latest server
# (or the first entry of lru.json offline) instead of the client's commit.
cat >"$t/wrapper" <<WRAP
#!/bin/sh
# Generated by $HSVR_NAME place.sh: run the VS Code CLI with the agent host pinned to its own commit.
VSCODE_CLI_INITIAL_AH_VERSION=$C exec "$HSVR_CLI_DIR/code-$C" "\$@"
WRAP
chmod 755 "$t/wrapper"
mv -f "$t/wrapper" "$HSVR_VSCODE_DIR/code-$C"
if [ $keep = no ]; then
  rm -rf "$HSVR_SERVERS_DIR/Stable-$C"
  mkdir "$HSVR_SERVERS_DIR/Stable-$C"
  mv "$t/server" "$HSVR_SERVERS_DIR/Stable-$C/server"
fi
write_lru "$C"
"$HSVR_VSCODE_DIR/code-$C" --version | head -n 1
if [ $keep = yes ]; then echo "kept the placed server of Stable-$C"; else echo "placed Stable-$C"; fi
echo "lru.json: $(cat "$HSVR_LRU")"
